export function getAllHelpSections(): HelpSectionItem[] {
  return HELP_CHAPTERS.flatMap((chapter) => chapter.sections);
}

export function getHelpSectionById(id: string): HelpSectionItem | undefined {
  return getAllHelpSections().find((section) => section.id === id);
}

export function filterHelpChapters(options: {
  query?: string;
  role?: HelpUserRole | 'all';
}): HelpChapter[] {
  const normalizedQuery = (options.query ?? '').trim().toLowerCase();
  const role = options.role ?? 'all';

  return HELP_CHAPTERS.map((chapter) => {
    const sections = chapter.sections.filter((section) => {
      if (role !== 'all' && !section.roles.includes(role)) {
        return false;
      }
      if (!normalizedQuery) {
        return true;
      }
      const haystack = [
        section.title,
        section.shortSummary,
        section.purpose,
        section.howItWorks,
        section.example,
        ...section.steps,
        ...section.limitations,
        ...section.keywords,
      ]
        .join(' ')
        .toLowerCase();
      return haystack.includes(normalizedQuery);
    });

    return { ...chapter, sections };
  }).filter((chapter) => chapter.sections.length > 0);
}
